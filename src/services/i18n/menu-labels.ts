export function useMenuLabel() {
    const locale = useLocale();

    return (title: string | React.ReactNode): string | React.ReactNode => {
        if (typeof title !== 'string') {
            return title;
        }
        if (locale === 'ar' && AR_LABELS[title]) {
            return AR_LABELS[title];
        }
        return title;
    };
}
